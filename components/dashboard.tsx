// ─── Helpers ─────────────────────────────────────────────────────────────────
const statusLabel = (s: string) => s.replaceAll("_", " ");
const fmt = (value: string) =>
  new Intl.DateTimeFormat(undefined, { dateStyle: "medium", timeStyle: "short" }).format(new Date(value));
const fmtDateOrTimestamp = (value?: string | number) => {
  if (!value) return "";
  try {
    const num = typeof value === "number" ? value : Number(value);
    const date = !isNaN(num) && num < 1e11 ? new Date(num * 1000) : new Date(value);
    return isNaN(date.getTime()) ? String(value) : new Intl.DateTimeFormat(undefined, { dateStyle: "medium" }).format(date);
  } catch {
    return String(value);
  }
};
const fmtTime = (value?: string) => {
  if (!value) return "";
  try {
    const d = new Date(value);
    return isNaN(d.getTime()) ? "" : new Intl.DateTimeFormat(undefined, { hour: "numeric", minute: "numeric", second: "numeric" }).format(d);
  } catch {
    return "";
  }
};

// ─── Dashboard ───────────────────────────────────────────────────────────────
export function Dashboard({ initialConfig }: { initialConfig?: Config | null } = {}) {
  const [jobs, setJobs] = useState<Job[]>([]);
  const [config, setConfig] = useState<Config | null>(initialConfig ?? null);
  const [detail, setDetail] = useState<Detail | null>(null);
  const [notice, setNotice] = useState("");
  const [lang, setLang] = useState<Lang>("en");
  const [theme, setTheme] = useState<Theme>("light");
  const [assistantOpen, setAssistantOpen] = useState(false);
  const [subscribers, setSubscribers] = useState<BeehiivSubscription[]>([]);
  const [loadingSubscribers, setLoadingSubscribers] = useState(false);
  const [subEmail, setSubEmail] = useState("");
  const [subSendWelcome, setSubSendWelcome] = useState(false);
  const [subTier, setSubTier] = useState<"free" | "premium">("free");
  const [addingSubscriber, setAddingSubscriber] = useState(false);
  const [subNotice, setSubNotice] = useState("");

  const t = i18n[lang];

  // Apply theme & dir to html element
  useEffect(() => {
    const html = document.documentElement;
    html.setAttribute("data-theme", theme);
  }, [theme]);

  useEffect(() => {
    const html = document.documentElement;
    html.setAttribute("lang", lang);
    html.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
  }, [lang]);

  const toggleTheme = () => setTheme((p) => (p === "light" ? "dark" : "light"));
  const toggleLang = () => setLang((p) => (p === "en" ? "ar" : "en"));

  const loadSubscribers = useCallback(async () => {
    setLoadingSubscribers(true);
    try {
      const res = await fetch("/api/beehiiv/subscribers?limit=50", { cache: "no-store" });
      if (res.ok) {
        const data = await res.json();
        setSubscribers(data.subscribers || []);
      }
    } catch (err) {
      console.error("[Dashboard] loadSubscribers error:", err);
    } finally {
      setLoadingSubscribers(false);
    }
  }, []);

  const load = useCallback(async () => {
    try {
      const [jobsRes, healthRes] = await Promise.all([
        fetch("/api/jobs", { cache: "no-store" }).catch(() => null),
        fetch("/api/health", { cache: "no-store" }).catch(() => null),
      ]);
      if (jobsRes && jobsRes.ok) {
        const jobsData = await jobsRes.json().catch(() => ({}));
        setJobs(jobsData.jobs || []);
      }
      if (healthRes && healthRes.ok) {
        const healthData = await healthRes.json().catch(() => ({}));
        setConfig(healthData.configuration || null);
        if (healthData.configuration?.beehiiv) {
          const subRes = await fetch("/api/beehiiv/subscribers?limit=50", { cache: "no-store" }).catch(() => null);
          if (subRes && subRes.ok) {
            const subData = await subRes.json().catch(() => ({}));
            if (subData.subscribers) setSubscribers(subData.subscribers);
          }
        }
      }
    } catch (err) {
      console.error("[Dashboard] load error:", err);
    }
  }, []);

  const open = useCallback(async (id: string) => {
    const res = await fetch(`/api/jobs/${id}`, { cache: "no-store" });
    if (res.ok) setDetail(await res.json());
  }, []);

  const activeJobId = detail?.job.id;

  useEffect(() => {
    const refresh = () => { void load(); if (activeJobId) void open(activeJobId); };
    const initial = window.setTimeout(refresh, 0);
    const timer = window.setInterval(refresh, 4000);
    return () => { window.clearTimeout(initial); window.clearInterval(timer); };
  }, [load, open, activeJobId]);

  async function addSubscriber(emailToAdd?: string, welcome?: boolean) {
    const email = (emailToAdd || subEmail).trim();
    if (!email || !email.includes("@")) {
      setSubNotice(lang === "ar" ? "يرجى إدخال بريد إلكتروني صحيح." : "Please enter a valid email address.");
      return false;
    }
    setAddingSubscriber(true);
    setSubNotice("");
    try {
      const res = await fetch("/api/beehiiv/subscribers", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({
          email,
          sendWelcomeEmail: welcome ?? subSendWelcome,
          tier: subTier,
        }),
      });
      const data = await res.json();
      if (res.ok && data.success) {
        setSubNotice(`${t.subscriberAdded}: ${email}`);
        setSubEmail("");
        await loadSubscribers();
        return true;
      } else {
        setSubNotice(data.error || "Failed to add subscriber.");
        return false;
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : "Failed to add subscriber.";
      setSubNotice(msg);
      return false;
    } finally {
      setAddingSubscriber(false);
    }
  }

  async function removeSubscriber(id: string, email: string) {
    if (!window.confirm(`${t.confirmDeleteSubscriber} (${email})`)) return;
    try {
      const res = await fetch(`/api/beehiiv/subscribers?id=${encodeURIComponent(id)}`, {
        method: "DELETE",
      });
      const data = await res.json();
      if (res.ok && data.success) {
        setSubscribers((prev) => prev.filter((s) => s.id !== id));
        setSubNotice(t.subscriberRemoved);
      } else {
        setSubNotice(data.error || "Failed to remove subscriber.");
      }
    } catch {
      setSubNotice("Failed to remove subscriber.");
    }
  }

  async function post(url: string, label: string) {
    setNotice("");
    const res = await fetch(url, { method: "POST" });
    const data = await res.json();
    setNotice(data.error || label);
    await load();
    if (data.job?.id) await open(data.job.id);
  }

  async function removeJob(id: string, e?: React.MouseEvent) {
    if (e) e.stopPropagation();
    if (!window.confirm(t.confirmDeleteVideo)) return;
    try {
      const res = await fetch(`/api/jobs/${id}`, { method: "DELETE" });
      if (res.ok) {
        if (detail?.job.id === id) setDetail(null);
        setJobs((prev) => prev.filter((j) => j.id !== id));
        setNotice(t.videoDeleted);
        void load();
      } else {
        const data = await res.json().catch(() => ({}));
        setNotice(data.error || "Failed to delete video.");
      }
    } catch {
      setNotice("Failed to delete video.");
    }
  }

  async function clearSamples() {
    const sampleJobs = jobs.filter((j) => j.isSample);
    if (!sampleJobs.length) return;
    if (!window.confirm(t.confirmClearSamples)) return;
    for (const sj of sampleJobs) {
      await fetch(`/api/jobs/${sj.id}`, { method: "DELETE" }).catch(() => {});
    }
    setJobs((prev) => prev.filter((j) => !j.isSample));
    if (detail?.job.isSample) setDetail(null);
    setNotice(t.samplesCleared);
    void load();
  }

  const connections: [string, boolean | undefined][] = [
    ["Frame.io", config?.frameio],
    ["Groq", config?.groq],
    ["Claude", config?.claude],
    ["Email", config?.email],
    ["Supabase", config?.supabase],
    ["Beehiiv", config?.beehiiv],
  ];

  const sentJobs = jobs.filter((j) => j.status === "sent");

  return (
    <main className="shell">
      {/* ── Masthead ── */}
      <header className="masthead">
        <div className="masthead-brand">
          <h1>{t.brand}</h1>
          <span className="masthead-route">{t.route}</span>
        </div>
        <div className="masthead-controls">
          <button
            className="assistant-btn"
            onClick={() => setAssistantOpen(true)}
            title={t.aiAssistant}
          >
            <span className="sparkle">✨</span>
            <span>{t.aiAssistant}</span>
          </button>
          <button className="lang-toggle" onClick={toggleLang} aria-label="Switch language" title="Switch language">
            {lang === "en" ? "عربي" : "English"}
          </button>
          <button className="icon-btn" onClick={toggleTheme} aria-label="Toggle theme" title="Toggle theme">
            {theme === "light" ? "🌙" : "☀️"}
          </button>
        </div>
      </header>


      {/* ── Hero ── */}
      <section className="hero">
        <p className="eyebrow">{t.eyebrowEditorial}</p>
        <h2 style={{ whiteSpace: "pre-line" }}>{t.heroHeadline}</h2>
        <div className="hero-actions">
          <button className="btn btn-ghost" onClick={() => void post("/api/manual/process", "Frame.io check queued.")}>
            {t.checkFrameio}
          </button>
          <button className="btn btn-primary" onClick={() => void post("/api/demo/sample", "Labelled sample created — no live services used.")}>
            {t.createSample}
          </button>
        </div>
      </section>

      {/* ── Notice ── */}
      {notice && <p className="notice" role="status">{notice}</p>}

      {/* ── Connections ── */}
      <section className="configuration" aria-label={t.connections}>
        <div className="configuration-header">
          <span className="section-label">{t.connections}</span>
        </div>
        <div className="connections">
          {connections.map(([name, active]) => (
            <div className={`connection${active ? " active" : ""}`} key={name}>
              <span className={active ? "dot ready" : "dot"} />
              <div className="connection-info">
                <strong>{name}</strong>
                <small>{active ? t.configured : t.needsSetup}</small>
              </div>
            </div>
          ))}
        </div>
      </section>

      {/* ── Jobs ── */}
      <section className="jobs">
        <div className="section-header">
          <div>
            <p className="eyebrow">{t.workspace}</p>
            <h2>{t.recentVideos}</h2>
          </div>
          <div style={{ display: "flex", alignItems: "center", gap: 12 }}>
            {jobs.some((j) => j.isSample) && (
              <button
                className="btn btn-ghost"
                style={{ padding: "6px 12px", fontSize: "0.85rem", color: "#dc2626" }}
                onClick={() => void clearSamples()}
                title={t.clearSamples}
              >
                🗑 {t.clearSamples}
              </button>
            )}
            <span className="section-header-count">
              {jobs.length} {jobs.length === 1 ? t.job : t.jobs}
            </span>
          </div>
        </div>

        {jobs.length ? (
          <div className="job-list">
            {jobs.map((job) => (
              <div
                className="job-row"
                key={job.id}
                onClick={() => void open(job.id)}
                role="button"
                tabIndex={0}
                onKeyDown={(e) => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); void open(job.id); } }}
              >
                <div className="file">
                  <strong>{job.filename}</strong>
                  <small>{fmt(job.createdAt)}{job.isSample ? " · SAMPLE" : ""}</small>
                </div>
                <div className="duration">
                  {job.durationSeconds ? `${Math.round(job.durationSeconds)}s` : "—"}
                </div>
                <span className={`pill ${job.status}`}>{statusLabel(job.status)}</span>
                <button
                  type="button"
                  className="row-delete-btn"
                  onClick={(e) => void removeJob(job.id, e)}
                  title={t.deleteVideo}
                  aria-label={t.deleteVideo}
                >
                  🗑
                </button>
                <span className="open-arrow">→</span>
              </div>
            ))}
          </div>
        ) : (
          <div className="empty">
            <p className="empty-title">{t.noVideos}</p>
            <p className="empty-sub">{t.noVideosSub}</p>
          </div>
        )}
      </section>

      {/* ── Sent emails ── */}
      <section className="sent-emails">
        <div className="section-header">
          <div>
            <p className="eyebrow">{t.archive}</p>
            <h2>{t.sentEmails}</h2>
          </div>
          <span className="section-header-count">
            {sentJobs.length} {sentJobs.length === 1 ? t.emailCountSingular : t.emailCountPlural}
          </span>
        </div>

        {sentJobs.length ? (
          <div className="job-list">
            {sentJobs.map((job) => (
              <div
                className="job-row"
                key={`sent-${job.id}`}
                onClick={() => void open(job.id)}
                role="button"
                tabIndex={0}
                onKeyDown={(e) => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); void open(job.id); } }}
              >
                <div className="file">
                  <strong>{job.draftSubject || job.filename}</strong>
                  <small>
                    {job.recipientEmail ? `${t.to}: ${job.recipientEmail} · ` : ""}
                    {fmt(job.updatedAt || job.createdAt)} · {job.filename}
                  </small>
                </div>
                <div className="duration">
                  {job.durationSeconds ? `${Math.round(job.durationSeconds)}s` : "—"}
                </div>
                <span className="pill sent">{t.sent}</span>
                <button
                  type="button"
                  className="row-delete-btn"
                  onClick={(e) => void removeJob(job.id, e)}
                  title={t.deleteVideo}
                  aria-label={t.deleteVideo}
                >
                  🗑
                </button>
                <span className="open-arrow">→</span>
              </div>
            ))}
          </div>
        ) : (
          <div className="empty">
            <p className="empty-title">{t.noSentEmails}</p>
            <p className="empty-sub">{t.noSentEmailsSub}</p>
          </div>
        )}
      </section>


      {/* ── Beehiiv Audience & Subscribers ── */}
      <section className="beehiiv-audience" aria-label={t.beehiivAudience}>
        <div className="section-header">
          <div>
            <p className="eyebrow">{t.beehiivAudienceEyebrow}</p>
            <h2>{t.beehiivAudience}</h2>
          </div>
          <div style={{ display: "flex", alignItems: "center", gap: 12 }}>
            <button
              id="beehiiv-refresh-subscribers-btn"
              type="button"
              className="btn btn-ghost btn-sm"
              disabled={loadingSubscribers}
              onClick={() => void loadSubscribers()}
              title={t.refreshSubscribers}
            >
              {loadingSubscribers ? (
                <>
                  <span className="spinner" style={{ width: 11, height: 11 }} />
                  {t.refreshingSubscribers}
                </>
              ) : (
                `⟳ ${t.refreshSubscribers}`
              )}
            </button>
            <span className="section-header-count">
              {subscribers.length} {subscribers.length === 1 ? t.subscriber : t.subscribers}
            </span>
          </div>
        </div>

        <div className="beehiiv-audience-card">
          <form
            className="beehiiv-sub-form"
            onSubmit={(e) => {
              e.preventDefault();
              void addSubscriber();
            }}
          >
            <div className="beehiiv-sub-input-wrap">
              <span className="beehiiv-sub-icon">✉</span>
              <input
                id="beehiiv-new-subscriber-email"
                type="email"
                required
                className="beehiiv-sub-input"
                placeholder={t.subscriberEmailPlaceholder}
                value={subEmail}
                onChange={(e) => setSubEmail(e.target.value)}
                disabled={addingSubscriber}
              />
            </div>

            <div className="beehiiv-sub-options">
              <label className="beehiiv-checkbox-label">
                <input
                  id="beehiiv-welcome-email-checkbox"
                  type="checkbox"
                  checked={subSendWelcome}
                  onChange={(e) => setSubSendWelcome(e.target.checked)}
                />
                <span>{t.sendWelcomeEmail}</span>
              </label>

              <select
                id="beehiiv-tier-select"
                className="beehiiv-select"
                value={subTier}
                onChange={(e) => setSubTier(e.target.value as "free" | "premium")}
              >
                <option value="free">{t.tierFree}</option>
                <option value="premium">{t.tierPremium}</option>
              </select>

              <button
                id="beehiiv-add-subscriber-btn"
                type="submit"
                className="btn btn-primary"
                disabled={addingSubscriber || !subEmail}
              >
                {addingSubscriber ? (
                  <>
                    <span className="spinner" style={{ width: 12, height: 12 }} />
                    {t.addingSubscriber}
                  </>
                ) : (
                  `✦ ${t.addSubscriber}`
                )}
              </button>
            </div>
          </form>

          {subNotice && (
            <p className="notice" role="status" style={{ margin: "4px 0 0" }}>
              {subNotice}
            </p>
          )}

          {!config?.beehiiv && (
            <p className="notice" style={{ margin: "4px 0 0", fontSize: 12 }}>
              {lang === "ar"
                ? "تنبيه: يتطلب تفعيل تكامل Beehiiv ضبط BEEHIIV_API_KEY و BEEHIIV_PUBLICATION_ID في ملف local.env."
                : "Note: Beehiiv credentials must be configured in local.env (BEEHIIV_API_KEY and BEEHIIV_PUBLICATION_ID)."}
            </p>
          )}

          <div className="beehiiv-subscriber-list-wrap">
            {subscribers.length ? (
              <div className="beehiiv-subscriber-list">
                {subscribers.map((sub) => {
                  const initial = (sub.email.charAt(0) || "U").toUpperCase();
                  const dateStr = fmtDateOrTimestamp(sub.created);
                  return (
                    <div className="beehiiv-sub-row" key={sub.id}>
                      <div className="beehiiv-sub-avatar">{initial}</div>
                      <div className="beehiiv-sub-info">
                        <strong>{sub.email}</strong>
                        {dateStr && <small>{dateStr}</small>}
                      </div>
                      <span className={`pill ${sub.tier === "premium" ? "ready_for_review" : ""}`} style={{ fontSize: 10 }}>
                        {sub.tier === "premium" ? t.tierPremium : t.tierFree}
                      </span>
                      <span className={`pill ${sub.status === "active" ? "sent" : ""}`} style={{ fontSize: 10 }}>
                        {sub.status === "active" ? t.statusActive : sub.status === "validating" ? t.statusValidating : sub.status}
                      </span>
                      <button
                        type="button"
                        className="row-delete-btn"
                        onClick={() => void removeSubscriber(sub.id, sub.email)}
                        title={t.confirmDeleteSubscriber}
                        aria-label={t.confirmDeleteSubscriber}
                      >
                        🗑
                      </button>
                    </div>
                  );
                })}
              </div>
            ) : (
              <div className="empty" style={{ margin: "16px 0 0" }}>
                <p className="empty-title">{t.noSubscribers}</p>
                <p className="empty-sub">{t.noSubscribersSub}</p>
              </div>
            )}
          </div>
        </div>
      </section>
      {/* ── Drawer ── */}
      {detail && (
        <>
          <div className="drawer-backdrop" onClick={() => setDetail(null)} />
          <JobPanel
            key={detail.job.id}
            detail={detail}
            close={() => setDetail(null)}
            refresh={() => void open(detail.job.id)}
            onDelete={() => void removeJob(detail.job.id)}
            setNotice={setNotice}
            t={t}
            lang={lang}
            beehiivConfigured={Boolean(config?.beehiiv)}
            onSubscriberAdded={() => void loadSubscribers()}
          />
        </>
      )}

      {/* ── AI Assistant Panel ── */}
      <AssistantPanel
        open={assistantOpen}
        onClose={() => setAssistantOpen(false)}
        onOpenDraft={(jobId) => {
          void open(jobId);
        }}
        lang={lang}
      />
    </main>
  );
}

// ─── Job Panel ───────────────────────────────────────────────────────────────
function JobPanel({
  detail, close, refresh, onDelete, setNotice, t, lang, beehiivConfigured, onSubscriberAdded,
}: {
  detail: Detail;
  close: () => void;
  refresh: () => void;
  onDelete: () => void;
  setNotice: (v: string) => void;
  t: typeof i18n[Lang];
  lang: Lang;
  beehiivConfigured?: boolean;
  onSubscriberAdded?: () => void;
}) {
  const [prevRemoteDraft, setPrevRemoteDraft] = useState<Draft | null>(detail.draft);
  const [draft, setDraft] = useState<Draft | null>(detail.draft);

  if (detail.draft !== prevRemoteDraft) {
    setPrevRemoteDraft(detail.draft);
    if (detail.draft) {
      setDraft(detail.draft);
    }
  }

  const [panelNotice, setPanelNotice] = useState("");
  const [saving, setSaving] = useState(false);
  const [confirming, setConfirming] = useState(false);
  const [viewMode, setViewMode] = useState<"editor" | "preview">("editor");
  const [coWorking, setCoWorking] = useState<string | null>(null);
  const [angles, setAngles] = useState<Array<{ angle: string; subject: string; headline: string }> | null>(null);
  const [factCheck, setFactCheck] = useState<{
    score: number; allGrounded: boolean;
    items: Array<{ statement: string; isGrounded: boolean; transcriptEvidence?: string }>;
  } | null>(null);

  const set = (key: keyof Draft, value: string) =>
    setDraft((cur) => (cur ? { ...cur, [key]: value } : cur));

  async function save() {
    if (!draft) return;
    setSaving(true);
    setPanelNotice("");
    try {
      const res = await fetch(`/api/jobs/${detail.job.id}`, {
        method: "PATCH", headers: { "content-type": "application/json" }, body: JSON.stringify(draft),
      });
      const data = await res.json();
      if (data.error) {
        setPanelNotice(data.error);
        setNotice(data.error);
      } else {
        setDraft(data.draft);
        setPrevRemoteDraft(data.draft);
        setPanelNotice("Draft saved successfully.");
        setNotice("Draft saved.");
        refresh();
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : "Failed to save draft.";
      setPanelNotice(msg);
      setNotice(msg);
    } finally {
      setSaving(false);
    }
  }

  async function retry() {
    const res = await fetch(`/api/jobs/${detail.job.id}/retry`, { method: "POST" });
    const data = await res.json();
    setPanelNotice(data.error || "Retry queued.");
    setNotice(data.error || "Retry queued.");
    refresh();
  }

  async function send() {
    setSaving(true);
    setPanelNotice("");
    try {
      const res = await fetch(`/api/jobs/${detail.job.id}/send`, {
        method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ confirm: true, draft }),
      });
      const data = await res.json();
      setConfirming(false);
      if (data.error) {
        setPanelNotice(data.error);
        setNotice(data.error);
      } else {
        setPanelNotice("Newsletter sent successfully!");
        setNotice("Email accepted by provider.");
        refresh();
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : "Send failed.";
      setPanelNotice(msg);
      setNotice(msg);
    } finally {
      setSaving(false);
    }
  }

  const [pushingBeehiiv, setPushingBeehiiv] = useState(false);
  const [refreshingStats, setRefreshingStats] = useState(false);
  const [prevRemoteBeehiivPost, setPrevRemoteBeehiivPost] = useState<BeehiivPost | null>(detail.beehiivPost || null);
  const [beehiivPost, setBeehiivPost] = useState<BeehiivPost | null>(detail.beehiivPost || null);
  const [beehiivAction, setBeehiivAction] = useState<"draft" | "publish" | "schedule">("draft");
  const [scheduledDateTime, setScheduledDateTime] = useState<string>("");

  if (detail.beehiivPost !== prevRemoteBeehiivPost) {
    setPrevRemoteBeehiivPost(detail.beehiivPost || null);
    setBeehiivPost(detail.beehiivPost || null);
    if (detail.beehiivPost?.scheduledAt) {
      try {
        const d = new Date(detail.beehiivPost.scheduledAt);
        const pad = (n: number) => String(n).padStart(2, "0");
        setScheduledDateTime(`${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`);
        setBeehiivAction("schedule");
      } catch {}
    } else if (detail.beehiivPost?.status === "confirmed") {
      setBeehiivAction("publish");
    } else {
      setBeehiivAction("draft");
    }
  }

  async function pushToBeehiiv(actionOverride?: "draft" | "publish" | "schedule") {
    if (!draft) return;
    const action = actionOverride || beehiivAction;
    if (action === "schedule" && !scheduledDateTime) {
      const msg = lang === "ar" ? "يرجى تحديد تاريخ ووقت الجدولة." : "Please select a date and time to schedule publication.";
      setPanelNotice(msg);
      setNotice(msg);
      return;
    }

    setPushingBeehiiv(true);
    setPanelNotice("");
    try {
      const res = await fetch(`/api/jobs/${detail.job.id}/beehiiv`, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({
          action,
          scheduledAt: action === "schedule" ? new Date(scheduledDateTime).toISOString() : undefined,
          draft,
        }),
      });
      const data = await res.json();
      if (data.error) {
        setPanelNotice(data.error);
        setNotice(data.error);
      } else {
        setBeehiivPost(data.post || { id: data.postId, previewUrl: data.previewUrl, webUrl: data.webUrl, status: action === "draft" ? "draft" : "confirmed" });
        const label = action === "publish" ? t.statusPublished : action === "schedule" ? t.statusScheduled : t.statusDraft;
        const successMsg = `${t.beehiivSuccess} [${label}] (ID: ${data.postId})`;
        setPanelNotice(successMsg);
        setNotice(successMsg);
        refresh();
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : "Failed to sync with Beehiiv.";
      setPanelNotice(msg);
      setNotice(msg);
    } finally {
      setPushingBeehiiv(false);
    }
  }

  async function refreshBeehiivMetrics() {
    setRefreshingStats(true);
    try {
      const res = await fetch(`/api/jobs/${detail.job.id}/beehiiv`);
      const data = await res.json();
      if (data.post) {
        setBeehiivPost(data.post);
        const msg = lang === "ar" ? "تم تحديث إحصاءات Beehiiv." : "Beehiiv metrics refreshed.";
        setPanelNotice(msg);
        setNotice(msg);
      }
    } catch {
      const msg = lang === "ar" ? "تعذر تحديث الإحصاءات." : "Could not refresh metrics.";
      setPanelNotice(msg);
      setNotice(msg);
    } finally {
      setRefreshingStats(false);
    }
  }

  const [quickAddingBeehiiv, setQuickAddingBeehiiv] = useState(false);

  async function handleQuickAddRecipient() {
    if (!draft?.recipientEmail) return;
    setQuickAddingBeehiiv(true);
    try {
      const res = await fetch("/api/beehiiv/subscribers", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({
          email: draft.recipientEmail,
          sendWelcomeEmail: false,
          tier: "free",
        }),
      });
      const data = await res.json();
      if (res.ok && data.success) {
        const msg = `${t.subscriberAdded}: ${draft.recipientEmail}`;
        setPanelNotice(msg);
        setNotice(msg);
        onSubscriberAdded?.();
      } else {
        setPanelNotice(data.error || "Failed to add to Beehiiv.");
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : "Failed to add to Beehiiv.";
      setPanelNotice(msg);
    } finally {
      setQuickAddingBeehiiv(false);
    }
  }

  async function callEditorial(payload: Record<string, unknown>) {
    const res = await fetch(`/api/jobs/${detail.job.id}/editorial`, {
      method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(payload),
    });
    return res.json();
  }

  async function requestHeadlines() {
    setCoWorking(lang === "ar" ? "جاري توليد الزوايا…" : "Generating angles…");
    try {
      const data = await callEditorial({ action: "headlines" });
      if (data.angles) setAngles(data.angles);
      else setNotice(data.error || "Could not generate headline angles.");
    } finally { setCoWorking(null); }
  }

  async function requestTone(tone: "warmer" | "punchier" | "more_reflective") {
    setCoWorking(lang === "ar" ? `جاري ضبط النبرة (${tone})…` : `Adjusting tone (${tone})…`);
    try {
      const data = await callEditorial({ action: "tone", tone });
      if (data.draft) {
        setDraft(data.draft);
        setPrevRemoteDraft(data.draft);
        setNotice(`Draft rewritten with ${tone} tone.`);
      } else setNotice(data.error || "Could not adjust tone.");
    } finally { setCoWorking(null); }
  }

  async function requestFactCheck() {
    setCoWorking(lang === "ar" ? "جاري التحقق من المصادر…" : "Verifying grounding against transcript…");
    try {
      const data = await callEditorial({ action: "factcheck" });
      if (data.check) setFactCheck(data.check);
      else setNotice(data.error || "Grounding check failed.");
    } finally { setCoWorking(null); }
  }

  function applyHeadline(angle: { subject: string; headline: string }) {
    setDraft((cur) => cur ? { ...cur, subject: angle.subject, headline: angle.headline } : cur);
    setAngles(null);
    setNotice("Headline & subject updated.");
  }

  const steps = ["received", "downloading", "transcribing", "drafting", "ready_for_review", "sending", "sent"];

  return (
    <aside className="drawer" aria-label={t.jobDetail}>
      <div className="drawer-inner">
        {/* Head */}
        <div className="drawer-head">
          <div>
            <p className="eyebrow">{t.jobDetail}</p>
            <h2>{detail.job.filename}</h2>
          </div>
          <div style={{ display: "flex", alignItems: "center", gap: 8 }}>
            <button
              type="button"
              className="row-delete-btn"
              onClick={onDelete}
              aria-label={t.deleteVideo}
              title={t.deleteVideo}
              style={{ fontSize: 16 }}
            >
              🗑
            </button>
            <button className="icon-btn" onClick={close} aria-label="Close" style={{ fontSize: 20 }}>✕</button>
          </div>
        </div>

        {panelNotice && (
          <p className="notice" role="status" style={{ margin: "12px 0" }}>{panelNotice}</p>
        )}


        {/* Progress */}
        <div className="progress">
          {steps.map((step) => (
            <span className={detail.job.status === step ? "current" : ""} key={step}>
              {statusLabel(step)}
            </span>
          ))}
        </div>

        {/* Alerts */}
        {detail.job.isSample && (
          <div className="alert alert-warn">{t.sampleMode}</div>
        )}
        {detail.job.errorMessage && (
          <div className="alert alert-err">
            <strong>{t.actionNeeded}</strong>
            <p style={{ margin: "4px 0 10px", fontSize: 13 }}>{detail.job.errorMessage}</p>
            <button className="btn btn-ghost btn-sm" onClick={() => void retry()}>{t.retryProcessing}</button>
          </div>
        )}

        {/* Source meta */}
        <div className="source-meta">
          <span>{t.assetId}<b>{detail.job.id.slice(0, 8)}…</b></span>
          <span>{t.duration}<b>{detail.job.durationSeconds ? `${Math.round(detail.job.durationSeconds)} ${t.seconds}` : t.pending}</b></span>
          <span>{t.status}<b>{statusLabel(detail.job.status)}</b></span>
        </div>

        {/* Transcript */}
        {detail.transcript && (
          <section className="transcript">
            <p className="eyebrow" style={{ marginBottom: 8 }}>{t.groqTranscript}</p>
            <p>{detail.transcript.text}</p>
          </section>
        )}

        {/* Editor or waiting */}
        {draft ? (
          <section className="editor">
            <div className="editor-top">
              <div>
                <p className="eyebrow">{t.humanApproval}</p>
                <h3>{t.newsletterDraft}</h3>
              </div>
              <span className={`pill ${draft.status}`}>{draft.status}</span>
            </div>

            {/* AI toolbar */}
            <div className="ai-toolbar">
              <div className="ai-toolbar-head">
                <span className="eyebrow">{t.aiCoEditor}</span>
                {coWorking && (
                  <span className="ai-working">
                    <span className="spinner" />
                    {coWorking}
                  </span>
                )}
              </div>
              <div className="ai-actions">
                <button className="btn btn-subtle btn-sm" disabled={!!coWorking} onClick={() => void requestHeadlines()}>
                  ✦ {t.headlines}
                </button>
                <div className="tone-group">
                  <button className="btn btn-subtle" disabled={!!coWorking} onClick={() => void requestTone("warmer")}>{t.warm}</button>
                  <button className="btn btn-subtle" disabled={!!coWorking} onClick={() => void requestTone("punchier")}>{t.punchy}</button>
                  <button className="btn btn-subtle" disabled={!!coWorking} onClick={() => void requestTone("more_reflective")}>{t.reflective}</button>
                </div>
                <button className="btn btn-subtle btn-sm" disabled={!!coWorking} onClick={() => void requestFactCheck()}>
                  ◉ {t.groundingCheck}
                </button>
              </div>
            </div>

            {/* Headline cards */}
            {angles && (
              <div className="headline-cards">
                <div className="headline-cards-head">
                  <strong>{t.suggestedAngles}</strong>
                  <button className="btn btn-subtle btn-xs" onClick={() => setAngles(null)}>✕</button>
                </div>
                {angles.map((item, idx) => (
                  <div key={idx} className="headline-card">
                    <div className="headline-card-meta">
                      <span className="eyebrow" style={{ color: "var(--text-3)" }}>{item.angle.toUpperCase()} {t.angle.toUpperCase()}</span>
                      <button className="btn btn-subtle btn-xs" onClick={() => applyHeadline(item)}>{t.apply}</button>
                    </div>
                    <strong>{item.headline}</strong>
                    <small>{t.subject}: {item.subject}</small>
                  </div>
                ))}
              </div>
            )}

            {/* Fact check */}
            {factCheck && (
              <div className="factcheck-panel">
                <div className="factcheck-head">
                  <span className={`factcheck-score ${factCheck.allGrounded ? "pass" : "review"}`}>
                    {factCheck.score}% · {factCheck.allGrounded ? t.groundedAll : t.groundedWarn}
                  </span>
                  <button className="btn btn-subtle btn-xs" onClick={() => setFactCheck(null)}>✕</button>
                </div>
                <div className="factcheck-body">
                  {factCheck.items.map((item, idx) => (
                    <div key={idx} className="factcheck-item">
                      <span>{item.isGrounded ? t.grounded : t.needsCheck} {item.statement}</span>
                      {item.transcriptEvidence && (
                        <code>{t.transcriptQuote} &ldquo;{item.transcriptEvidence}&rdquo;</code>
                      )}
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* View tabs */}
            <div className="view-tabs">
              <button className={`view-tab${viewMode === "editor" ? " active" : ""}`} onClick={() => setViewMode("editor")}>
                {t.editorialForm}
              </button>
              <button className={`view-tab${viewMode === "preview" ? " active" : ""}`} onClick={() => setViewMode("preview")}>
                {t.publicationPreview}
              </button>
            </div>

            {viewMode === "editor" ? (
              <>
                <div className="field"><label>{t.subject}<input value={draft.subject} onChange={(e) => set("subject", e.target.value)} /></label></div>
                <div className="field"><label>{t.previewText}<input value={draft.previewText} onChange={(e) => set("previewText", e.target.value)} /></label></div>
                <div className="field"><label>{t.headline}<input value={draft.headline} onChange={(e) => set("headline", e.target.value)} /></label></div>
                <div className="field"><label>{t.storyBody}<textarea rows={12} value={draft.body} onChange={(e) => set("body", e.target.value)} /></label></div>
                <div className="field"><label>{t.closing}<input value={draft.closing || ""} onChange={(e) => set("closing", e.target.value)} /></label></div>
                <div className="field">
                  <div style={{ display: "flex", justifyContent: "space-between", alignItems: "baseline", marginBottom: 6 }}>
                    <label htmlFor="job-recipient-email" style={{ margin: 0 }}>{t.recipientEmail}</label>
                    {beehiivConfigured && draft.recipientEmail && draft.recipientEmail.includes("@") && (
                      <button
                        id="quick-add-recipient-beehiiv-btn"
                        type="button"
                        className="btn btn-subtle btn-xs"
                        style={{ color: "var(--brand)", fontWeight: 600 }}
                        onClick={() => void handleQuickAddRecipient()}
                        disabled={quickAddingBeehiiv}
                        title={t.quickAddRecipientToBeehiiv}
                      >
                        {quickAddingBeehiiv ? (
                          <>
                            <span className="spinner" style={{ width: 10, height: 10 }} />
                            {t.addingSubscriber}
                          </>
                        ) : (
                          `✦ ${t.quickAddRecipientToBeehiiv}`
                        )}
                      </button>
                    )}
                  </div>
                  <input
                    id="job-recipient-email"
                    type="email"
                    value={draft.recipientEmail || ""}
                    onChange={(e) => set("recipientEmail", e.target.value)}
                    placeholder="editor@example.com"
                  />
                </div>
              </>
            ) : (
              <div className="newsletter-artifact">
                <div className="newsletter-masthead">
                  <h4>DOSE OF SOCIETY</h4>
                  <p>{t.everyday}</p>
                </div>
                <div className="newsletter-meta">
                  <span>{t.source}: {detail.job.filename}</span> &nbsp;·&nbsp; <span>{t.issue}: #{detail.job.id.slice(0, 6)}</span>
                </div>
                <h1 className="newsletter-title">{draft.headline}</h1>
                <p className="newsletter-dek">{draft.previewText}</p>
                <div className="newsletter-body">
                  {draft.body.split("\n\n").map((para, i) => <p key={i}>{para}</p>)}
                </div>
                {draft.closing && (
                  <div className="newsletter-closing-card">
                    <b>{t.editorialReflection}</b>
                    <p style={{ margin: 0, whiteSpace: "pre-wrap" }}>{draft.closing}</p>
                  </div>
                )}
                <div className="newsletter-footer">
                  <p style={{ margin: "0 0 4px" }}>{t.footerLine1}</p>
                  <p style={{ margin: 0 }}>{t.footerLine2}</p>
                </div>
              </div>
            )}

            {/* Beehiiv Publishing & Analytics Card */}
            {beehiivConfigured && (
              <div className="beehiiv-card">
                <div className="beehiiv-head">
                  <div className="beehiiv-head-title">
                    <span>✦</span>
                    <span>{t.beehiivControls}</span>
                  </div>
                  {beehiivPost && (
                    <span className={`beehiiv-badge ${beehiivPost.scheduledAt ? "scheduled" : beehiivPost.status}`}>
                      {beehiivPost.scheduledAt
                        ? `⏱ ${t.statusScheduled}`
                        : beehiivPost.status === "confirmed"
                        ? `✓ ${t.statusPublished}`
                        : `✎ ${t.statusDraft}`}
                    </span>
                  )}
                </div>

                <div className="beehiiv-body">
                  {beehiivPost && (
                    <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", flexWrap: "wrap", gap: 8, fontSize: 13 }}>
                      <div style={{ display: "flex", gap: 14, alignItems: "center" }}>
                        {beehiivPost.previewUrl && (
                          <a href={beehiivPost.previewUrl} target="_blank" rel="noopener noreferrer" style={{ color: "var(--brand)", fontWeight: 600, textDecoration: "underline" }}>
                            {t.viewOnBeehiiv}
                          </a>
                        )}
                        {beehiivPost.webUrl && (
                          <a href={beehiivPost.webUrl} target="_blank" rel="noopener noreferrer" style={{ color: "var(--text-2)", fontWeight: 500, textDecoration: "underline" }}>
                            {t.liveWebPost}
                          </a>
                        )}
                      </div>
                      {beehiivPost.scheduledAt && (
                        <div style={{ fontSize: 12, color: "var(--warn)", fontWeight: 600 }}>
                          {t.scheduledFor}: {fmt(beehiivPost.scheduledAt)}
                        </div>
                      )}
                    </div>
                  )}

                  {beehiivPost && (
                    <div style={{ display: "grid", gap: 8 }}>
                      <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center" }}>
                        <span style={{ fontSize: 11, fontWeight: 700, letterSpacing: "0.06em", textTransform: "uppercase", color: "var(--text-3)" }}>
                          {t.performanceMetrics}
                        </span>
                        <button
                          type="button"
                          className="btn btn-subtle btn-xs"
                          disabled={refreshingStats}
                          onClick={() => void refreshBeehiivMetrics()}
                          title="Fetch latest open and click metrics from Beehiiv API"
                        >
                          {refreshingStats ? (
                            <>
                              <span className="spinner" style={{ width: 10, height: 10 }} />
                              {t.refreshingStats}
                            </>
                          ) : (
                            `⟳ ${t.refreshStats}`
                          )}
                        </button>
                      </div>

                      <div className="beehiiv-metrics-grid">
                        <div className="beehiiv-metric-box">
                          <span className="beehiiv-metric-label">{t.recipients}</span>
                          <span className="beehiiv-metric-value">{beehiivPost.stats?.email?.recipients ?? 0}</span>
                          <span className="beehiiv-metric-sub">{beehiivPost.stats?.email?.delivered ?? 0} delivered</span>
                        </div>
                        <div className="beehiiv-metric-box">
                          <span className="beehiiv-metric-label">{t.openRate}</span>
                          <span className="beehiiv-metric-value">
                            {beehiivPost.stats?.email?.openRate != null ? `${(beehiivPost.stats.email.openRate * 100).toFixed(1)}%` : "0.0%"}
                          </span>
                          <span className="beehiiv-metric-sub">{beehiivPost.stats?.email?.uniqueOpens ?? 0} unique opens</span>
                        </div>
                        <div className="beehiiv-metric-box">
                          <span className="beehiiv-metric-label">{t.clickRate}</span>
                          <span className="beehiiv-metric-value">
                            {beehiivPost.stats?.email?.clickRate != null ? `${(beehiivPost.stats.email.clickRate * 100).toFixed(1)}%` : "0.0%"}
                          </span>
                          <span className="beehiiv-metric-sub">{beehiivPost.stats?.email?.uniqueClicks ?? 0} clicks</span>
                        </div>
                        <div className="beehiiv-metric-box">
                          <span className="beehiiv-metric-label">{t.webViews}</span>
                          <span className="beehiiv-metric-value">{beehiivPost.stats?.web?.views ?? 0}</span>
                          <span className="beehiiv-metric-sub">web reads</span>
                        </div>
                      </div>
                    </div>
                  )}

                  <div className="beehiiv-controls-bar">
                    <div className="beehiiv-mode-toggle">
                      <button
                        type="button"
                        className={`beehiiv-mode-btn ${beehiivAction === "draft" ? "active" : ""}`}
                        onClick={() => setBeehiivAction("draft")}
                      >
                        {t.modeDraft}
                      </button>
                      <button
                        type="button"
                        className={`beehiiv-mode-btn ${beehiivAction === "publish" ? "active" : ""}`}
                        onClick={() => setBeehiivAction("publish")}
                      >
                        {t.modePublish}
                      </button>
                      <button
                        type="button"
                        className={`beehiiv-mode-btn ${beehiivAction === "schedule" ? "active" : ""}`}
                        onClick={() => setBeehiivAction("schedule")}
                      >
                        {t.modeSchedule}
                      </button>
                    </div>

                    {beehiivAction === "schedule" && (
                      <input
                        type="datetime-local"
                        className="beehiiv-date-input"
                        value={scheduledDateTime}
                        onChange={(e) => setScheduledDateTime(e.target.value)}
                        title={t.selectScheduleTime}
                      />
                    )}

                    <button
                      type="button"
                      className="btn btn-primary btn-sm"
                      disabled={pushingBeehiiv}
                      onClick={() => void pushToBeehiiv()}
                      style={{ marginInlineStart: "auto" }}
                    >
                      {pushingBeehiiv ? (
                        <>
                          <span className="spinner" style={{ width: 11, height: 11 }} />
                          {t.pushingBeehiiv}
                        </>
                      ) : beehiivPost?.id ? (
                        beehiivAction === "publish"
                          ? `✦ ${t.publishToBeehiivNow}`
                          : beehiivAction === "schedule"
                          ? `⏱ ${t.scheduleOnBeehiiv}`
                          : `✦ ${t.syncBeehiivUpdates}`
                      ) : beehiivAction === "publish" ? (
                        `✦ ${t.publishToBeehiivNow}`
                      ) : beehiivAction === "schedule" ? (
                        `⏱ ${t.scheduleOnBeehiiv}`
                      ) : (
                        `✦ ${t.saveAsBeehiivDraft}`
                      )}
                    </button>
                  </div>
                </div>
              </div>
            )}

            {/* Actions */}
            <div className="editor-actions" style={{ flexWrap: "wrap", gap: 8 }}>
              <button className="btn btn-ghost" disabled={saving || draft.status === "sent"} onClick={() => void save()}>
                {saving ? t.saving : t.saveDraft}
              </button>
              <button className="btn btn-primary" disabled={draft.status === "sent"} onClick={() => setConfirming(true)}>
                {draft.status === "sent" ? t.sent : t.sendNewsletter}
              </button>
            </div>
          </section>
        ) : (
          <section className="waiting">
            <p className="eyebrow">{t.draft}</p>
            <h3>{detail.job.status === "failed" ? t.retryWhenReady : t.draftPending}</h3>
          </section>
        )}

        {/* Event log */}
        <section className="event-log">
          <p className="event-log-title">{t.eventLog}</p>
          {detail.events.length === 0 ? (
            <p style={{ opacity: 0.6, fontSize: "0.85rem", margin: "6px 0" }}>
              {statusLabel(detail.job.status)}
            </p>
          ) : (
            detail.events.map((event, idx) => {
              const timeStr = fmtTime(event.created_at);
              return (
                <div key={idx} className="event-item">
                  <div style={{ display: "flex", justifyContent: "space-between", alignItems: "baseline", gap: 8 }}>
                    <b>{statusLabel(event.status)}</b>
                    {timeStr && <span style={{ fontSize: "0.75rem", opacity: 0.55 }}>{timeStr}</span>}
                  </div>
                  <span>{event.message}</span>
                </div>
              );
            })
          )}
        </section>
      </div>

      {/* Confirm modal */}
      {confirming && draft && (
        <div className="confirm-overlay">
          <div className="confirm-box">
            <p className="eyebrow">{lang === "ar" ? "تأكيد نهائي" : "Final confirmation"}</p>
            <h3>{t.sendConfirmTitle}</h3>
            <p>
              {t.sendConfirmBody
                .replace("{email}", `${draft.recipientEmail || t.noRecipient}`)
                .replace("{subject}", draft.subject)}
            </p>
            <div className="confirm-actions">
              <button className="btn btn-ghost" onClick={() => setConfirming(false)}>{t.cancel}</button>
              <button className="btn btn-primary" onClick={() => void send()}>{t.confirmSend}</button>
            </div>
          </div>
        </div>
      )}
    </aside>
  );
}
